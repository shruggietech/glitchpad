import { createHash } from 'node:crypto';
import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const PDF_VERSION = '6.5.438';
export const PDF_WORKER_SHA256 =
  '8336aabf764cb08c818555a2fd2545e4fed10837146de927564875c93b3c4f83';
const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(join(root, 'apps/glitchpad/package.json'));
export const pdfPackageRoot = () =>
  dirname(require.resolve('pdfjs-dist/package.json'));
export const sha256 = (bytes) =>
  createHash('sha256').update(bytes).digest('hex');

export async function preparePdfAssets() {
  const packageRoot = pdfPackageRoot();
  const manifest = JSON.parse(
    await readFile(join(packageRoot, 'package.json'), 'utf8'),
  );
  if (manifest.version !== PDF_VERSION)
    throw new Error('Unreviewed PDF engine version');
  if (
    sha256(await readFile(join(packageRoot, 'legacy/build/pdf.worker.mjs'))) !==
    PDF_WORKER_SHA256
  )
    throw new Error('Unreviewed PDF worker bytes');
  const names = (await readdir(join(packageRoot, 'cmaps')))
    .filter((n) => /^[A-Za-z0-9_.-]+\.bcmap$/.test(n))
    .sort()
    .map((n) => 'cmaps/' + n);
  names.push(
    'standard_fonts/FoxitSymbol.pfb',
    'standard_fonts/FoxitDingbats.pfb',
  );
  const resources = {};
  const hashes = {};
  for (const name of names) {
    const bytes = await readFile(join(packageRoot, name));
    resources[name] = bytes.toString('base64');
    hashes[name] = sha256(bytes);
  }
  const output = join(root, 'apps/glitchpad/src/pdf-generated');
  await mkdir(output, { recursive: true });
  await writeFile(
    join(output, 'resources.ts'),
    '// Generated by scripts/prepare-pdf-assets.mjs from the exact locked package.\nexport const pdfResourceData: Readonly<Record<string, string>> = Object.freeze(' +
      JSON.stringify(resources) +
      ');\n',
    'utf8',
  );
  await writeFile(
    join(output, 'manifest.json'),
    JSON.stringify(
      {
        version: PDF_VERSION,
        worker_sha256: PDF_WORKER_SHA256,
        resources: hashes,
      },
      null,
      2,
    ) + '\n',
    'utf8',
  );
  return { version: PDF_VERSION, resources: names.length };
}

if (
  process.argv[1] &&
  fileURLToPath(import.meta.url) === resolve(process.argv[1])
)
  console.log(JSON.stringify(await preparePdfAssets()));
